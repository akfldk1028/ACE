def grid_triangles(xs, ys, surface):
    triangles = []
    for i, (x0, x1) in enumerate(zip(xs, xs[1:])):
        for j, (y0, y1) in enumerate(zip(ys, ys[1:])):
            a, b, c, d = [(x, y, surface(x, y))
                          for x, y in ((x0, y0), (x1, y0), (x1, y1), (x0, y1))]
            triangles.extend(((a, b, c), (a, c, d)) if (i+j) % 2 else ((a, b, d), (b, c, d)))
    return triangles


def render(triangles, scale=1, zoom=1):
    panel = Image.new('RGB', (int(64*zoom), int(64*zoom)), (255, 255, 255))
    triangles = [tuple(tuple(value*scale for value in point) for point in triangle)
                 for triangle in triangles]
    paint_mesh(panel, triangles, project=lambda x, y, z: (x/scale, y/scale),
               to_screen=lambda point: tuple(value*zoom for value in point), yaw=0, pitch=pi/2,
               palette=PALETTE, smooth_turn_cos=.9)
    return np.asarray(panel)


def edge_pixels(pixels):
    return np.all(pixels == PALETTE.edge, axis=2)


class MeshDepthEdgesTests(SimpleTestCase):
    def test_parallel_roof_depth_step_gets_an_edge_at_every_world_scale(self):
        # Same visible +Z normals on both sides, with no intervening wall pixel.
        for left_z, right_z in ((2, 5), (5, 2)):
            triangles = grid_triangles([8, 32], [8, 56], lambda x, y: left_z)
            triangles += grid_triangles([32, 56], [8, 56], lambda x, y: right_z)
            for scale in (1e-4, 1, 1e4):
                with self.subTest(scale=scale, left_z=left_z):
                    edges = edge_pixels(render(triangles, scale))
                    self.assertTrue(edges[12:52, 31:33].all())
                    self.assertFalse(edges[12:52, 12:29].any())
                    self.assertFalse(edges[12:52, 35:52].any())

    def test_coplanar_tessellation_and_continuous_steep_slope_are_seamless(self):
        for surface in (lambda x, y: 2, lambda x, y: 3*x + 2*y):
            for subdivisions in (2, 17):
                with self.subTest(surface=surface, subdivisions=subdivisions):
                    stations = np.linspace(8, 56, subdivisions)
                    pixels = render(grid_triangles(stations, stations, surface))
                    self.assertFalse(edge_pixels(pixels)[12:52, 12:52].any())

    def test_continuous_curved_tessellation_retains_smooth_shading(self):
        stations = np.linspace(8, 56, 25)
        for surface in (lambda x, y: .008*(x-32)**2,
                        lambda x, y: .008*((x-32)**2 + (y-32)**2),
                        lambda x, y: .008*((x-32)**2 - (y-32)**2)):
            with self.subTest(surface=surface):
                pixels = render(grid_triangles(stations, stations, surface))
                self.assertFalse(edge_pixels(pixels)[12:52, 12:52].any())
                self.assertGreater(len(np.unique(pixels[12:52, 12:52].reshape(-1, 3), axis=0)), 1)

    def test_continuous_shallow_fold_does_not_become_a_depth_seam(self):
        triangles = grid_triangles([8, 31.3, 56], [8, 56], lambda x, y: abs(x-31.3)*.1)
        self.assertFalse(edge_pixels(render(triangles))[12:52, 12:52].any())

    def test_multifacet_curved_roof_has_no_subpixel_depth_outlines(self):
        # Endpoint gradients do not bound every intervening triangle gradient.
        surface = lambda x, y: .2*np.sin((x-32)*.4)*np.sin((y-32)*.3)
        for count in (25, 49):
            stations = np.linspace(8, 56, count)
            triangles = grid_triangles(stations, stations, surface)
            for zoom in (.5, 1, 2):
                with self.subTest(count=count, zoom=zoom):
                    edges = edge_pixels(render(triangles, zoom=zoom))
                    start, end = int(12*zoom), int(52*zoom)
                    self.assertFalse(edges[start:end, start:end].any())

    def test_depth_visibility_uses_output_pixel_scale(self):
        triangles = grid_triangles([8, 32], [8, 56], lambda x, y: 2)
        triangles += grid_triangles([32, 56], [8, 56], lambda x, y: 2.75)
        # Same world-space separation is unresolved at 1 unit/pixel and
        # resolved at .5 units/pixel. This is a drawing policy, not a solid test.
        self.assertFalse(edge_pixels(render(triangles))[12:52, 31:33].any())
        self.assertTrue(edge_pixels(render(triangles, zoom=2))[24:104, 63:65].all())

    def test_actual_delivered_stack_upper_roof_has_no_internal_seam(self):
        from shapely.geometry import Point, Polygon
        from shapely.ops import unary_union
        from design.maas.massv2 import render as owner

        projected = np.array([owner._project(*point) for triangle in DELIVERED_STACK for point in triangle])
        lower, upper = projected.min(axis=0), projected.max(axis=0)
        zoom = 220 / max(upper-lower)
        to_screen = lambda point: tuple((np.asarray(point)-lower)*zoom+16)
        panel = Image.new('RGB', (256, 256), (255, 255, 255))
        paint_mesh(panel, DELIVERED_STACK, project=owner._project, to_screen=to_screen,
                   yaw=owner._YAW, pitch=owner._PITCH, palette=PALETTE, smooth_turn_cos=.9)
        top = unary_union([Polygon([to_screen(owner._project(*p)) for p in triangle])
                           for triangle in DELIVERED_STACK if all(p[2] == 10.8 for p in triangle)])
        interior = top.buffer(-3)
        edges = edge_pixels(np.asarray(panel))
        samples = [(x, y) for y in range(256) for x in range(256)
                   if interior.contains(Point(x+.5, y+.5))]
        self.assertGreater(len(samples), 100)
        self.assertFalse(any(edges[y, x] for x, y in samples))
